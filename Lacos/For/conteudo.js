/*
  O FOR é muito utilizado quando sabemos quantas vezes precisamos repetir uma ação

  ESTRUTURA:
  FOR(inicio;condicao;incremento){
  
  }
  
  O FOR possui três partes:

  1. INÍCIO: Criar o contador 
  2. CONDIÇÃO: Determina até quando repetir
  3. INCREMENTO: Atualiza o contador
  ******ATENÇÃO*******
  Precisamos utilizar o ; para separar essas partes


*/
// EXEMPLO: Contagem de 1 até 5

for(let i = 1; i <= 5; i++){
    console.log("Contagem", i)
}

// ENTENDO:
// let i = 1 -> começa em 1
// i <= 5 -> repete enquanto i for até 5
// i++ -> aumenta 1 após cada repetição